    def service_document(self, req: Request) -> Response:
        self.maybe_fault(req, "auth")
        self.container_effects(req, "auth")
        self.authenticate(req)
        self.check_rate()
        self.check_on_behalf_of(req)
        self.maybe_fault(req, "process")
        s = self.w.settings
        doc = {
            "@context": errtable.JSON_LD_CONTEXT,
            "@type": "ServiceDocument",
            "@id": f"{req.base_url}/sword/service-document",
            "root": f"{req.base_url}/sword/service-document",
            "dc:title": "sword-stub (mechanics rig, not WEKO)",
            "version": "http://purl.org/net/sword/3.0",
            "acceptArchiveFormat": s["accept_archive_format"],
            "acceptPackaging": s["accept_packaging"],
            "maxUploadSize": s["max_upload_size"],
            "onBehalfOf": bool(s["on_behalf_of"]),
        }
        self.w.log("INFO", "GET /sword/service-document -> 200")
