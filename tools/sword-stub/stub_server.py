class SwordError(Exception):
    """A coded error (`WEKO_SWORDSERVER_E_xxxx`)."""

    def __init__(self, code: str, log: str | None = None, **params: object) -> None:
        type_, status, message = errtable.describe(code, **params)
        super().__init__(message)
        self.code, self.type, self.status, self.message = code, type_, status, message
        self.log = log


class PlainError(Exception):
    """401 / 403 without a WEKO code (the blueprint's generic handlers)."""

    def __init__(self, status: int) -> None:
        super().__init__(status)
        self.status = status


class DropConnection(Exception):
    """The web container is stopped: answer nothing."""


class Fault(Exception):
    """An injected failure with an optional fake traceback."""

    def __init__(self, code: str, source: str) -> None:
        super().__init__(code)
        self.code, self.source = code, source


