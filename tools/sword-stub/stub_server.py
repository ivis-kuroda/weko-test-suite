class Part:
    def __init__(
        self, name: str | None, filename: str | None, content_type: str | None, data: bytes
    ):
        self.name, self.filename, self.content_type, self.data = name, filename, content_type, data


_PARAM = r'{key}=(?:"((?:[^"\\]|\\.)*)"|([^;\s]*))'


def _disp_param(header: str, key: str) -> str | None:
    match = re.search(r"(?:^|[;\s])" + _PARAM.format(key=key), header, re.IGNORECASE)
    if match is None:
        return None
    return match.group(1) if match.group(1) is not None else (match.group(2) or "")


def parse_multipart(content_type: str, body: bytes) -> list[Part]:
    """Binary-safe multipart/form-data parser. Parts without a boundary are none."""
    match = re.search(r'boundary=(?:"([^"]+)"|([^;\s]+))', content_type or "", re.IGNORECASE)
    if not match or "multipart/" not in content_type.lower():
        return []
    boundary = (match.group(1) or match.group(2)).encode()
    delimiter = b"--" + boundary
    parts: list[Part] = []
    for chunk in body.split(delimiter)[1:]:
        if chunk.startswith(b"--"):
            break
        chunk = chunk[2:] if chunk.startswith(b"\r\n") else chunk
        head, sep, data = chunk.partition(b"\r\n\r\n")
        if not sep:
            continue
        if data.endswith(b"\r\n"):
            data = data[:-2]
        headers: dict[str, str] = {}
        for line in head.decode("utf-8", "replace").split("\r\n"):
            if ":" in line:
                k, v = line.split(":", 1)
                headers[k.strip().lower()] = v.strip()
        disposition = headers.get("content-disposition", "")
        parts.append(
            Part(
                _disp_param(disposition, "name"),
                _disp_param(disposition, "filename"),
                headers.get("content-type"),
                data,
            )
        )
    return parts


