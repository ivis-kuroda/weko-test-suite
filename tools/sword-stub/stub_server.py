def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _validate_bag(archive: zipfile.ZipFile) -> str | None:
    """Reason a BagIt bag is invalid, or None."""
    names = set(archive.namelist())
    if "bagit.txt" not in names:
        return "Bag is invalid: bagit.txt is missing"
    for manifest in ("manifest-sha256.txt", "tagmanifest-sha256.txt"):
        if manifest not in names:
            if manifest.startswith("manifest"):
                return f"Bag is invalid: {manifest} is missing"
            continue
        for line in archive.read(manifest).decode("utf-8", "replace").splitlines():
            if not line.strip():
                continue
            checksum, _, path = line.partition("  ")
            if path not in names:
                return f"Bag is invalid: {path} is listed in {manifest} but missing"
            if _sha256(archive.read(path)) != checksum.strip():
                return f"Bag is invalid: checksum mismatch for {path}"
    return None


def detect_format(archive: zipfile.ZipFile, packaging: str) -> str:
    """`check_import_file_format`: returns JSON / XML / TSV/CSV or raises SwordError."""
    files = archive.namelist()
    if "SWORDBagIt" in packaging:
        if SWORD_METADATA_FILE in files:
            return "JSON"
        raise SwordError("1404", log="metadate/sword.json is not found in SWORDBagIt.")
    if "SimpleZip" in packaging:
        if ROCRATE_METADATA_FILE in files:
            return "JSON"
        if SWORD_METADATA_FILE in files:
            raise SwordError("1405", log="packaging format is SimpleZip, but sword.json is found.")
        if any("ro-crate-metadata.json" in name for name in files):
            raise SwordError("1406")
        seconds = [n.split("/")[1] for n in files if "/" in n and n.split("/")[1]]
        if any(s.endswith(".xml") for s in seconds):
            return "XML"
        if any(s.endswith((".tsv", ".csv")) for s in seconds):
            return "TSV/CSV"
        raise SwordError("1407")
    raise SwordError("1408", packaging=packaging)


def _json_items(
    archive: zipfile.ZipFile, packaging: str
) -> tuple[list[dict[str, Any]], str | None]:
    """Items of a JSON-LD package, or (items, error detail)."""
    reason = _validate_bag(archive)
    if reason:
        return [], reason
    path = (
        SWORD_METADATA_FILE if SWORD_METADATA_FILE in archive.namelist() else ROCRATE_METADATA_FILE
    )
    raw = archive.read(path)
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError as exc:
        return [], f"{path} is not UTF-8 (byte offset {exc.start})"
    try:
        doc = json.loads(text)
    except json.JSONDecodeError as exc:
        return [], f"{path} is not valid JSON (line {exc.lineno}, column {exc.colno})"
    root = next(
        (n for n in doc.get("@graph", []) if isinstance(n, dict) and n.get("@id") == "./"), None
    )
    if root is None:
        return [], f"{path} has no root dataset"
    item_id = root.get("identifier")
    return [{"id": str(item_id) if item_id else None, "title": root.get("name") or ""}], None


def _csv_items(archive: zipfile.ZipFile) -> tuple[list[dict[str, Any]], str | None]:
    names = sorted(
        n for n in archive.namelist() if "/" in n and n.split("/")[1].endswith((".csv", ".tsv"))
    )
    raw = archive.read(names[0])
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError:
        return [], f"{names[0]} is not UTF-8"
    delimiter = "\t" if names[0].endswith(".tsv") else ","
    rows = list(csv.reader(io.StringIO(text), delimiter=delimiter))
    if len(rows) < 2:
        return [], "no header in the import file"
    keys = rows[1]
    items = []
    for row in rows[5:]:
        if not any(row):
            continue
        record = dict(zip(keys, row, strict=False))
        items.append(
            {
                "id": record.get(".id") or None,
                "title": record.get(".metadata.title", ""),
            }
        )
    return items, None


def _xml_items(archive: zipfile.ZipFile) -> tuple[list[dict[str, Any]], str | None]:
    name = next(n for n in archive.namelist() if "/" in n and n.split("/")[1].endswith(".xml"))
    text = archive.read(name).decode("utf-8", "replace")
    match = re.search(r"<dc:title[^>]*>([^<]*)</dc:title>", text)
    if match is None:
        return [], f"{name} has no dc:title"
    return [{"id": None, "title": match.group(1)}], None


