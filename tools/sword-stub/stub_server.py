def run_helper(world: World, cmd: str, params: dict[str, Any]) -> dict[str, Any]:
    """The in-container helper contract (helpers/run.py) against the stub's state."""
    w = world
    with w.lock:
        if cmd == "list":
            return _helper_ok(sorted(HELPER_COMMANDS + ["list"]))
        if cmd == "ping":
            return _helper_ok(
                {"db_ok": True, "db_version": "stub", "packages": {}, "commit": "stub"}
            )
        if cmd == "create_user":
            email = params.get("email")
            if not isinstance(email, str) or "@" not in email:
                return _helper_fail("InvalidArgument", "email must be a non-empty string")
            previous = w.users.get(email)
            roles = list(params.get("roles") or [])
            w.users[email] = {"roles": sorted(set(roles) | set((previous or {}).get("roles", [])))}
            return _helper_ok(
                {
                    "id": len(w.users),
                    "created": previous is None,
                    "roles_added": [r for r in roles if r not in (previous or {}).get("roles", [])],
                    "previous": previous,
                }
            )
        if cmd == "create_token":
            email = params.get("user_email")
            name = params.get("name")
            if not isinstance(name, str) or not name:
                return _helper_fail("InvalidArgument", "name must be a non-empty string")
            user = w.users.get(email or "", {"roles": []})
            prefix = params.get("token_prefix", "WEKO_TEST_TOKEN_")
            existing = next((t for t, v in w.tokens.items() if v.get("name") == name), None)
            scopes = list(params.get("scopes") or [])
            if existing:
                previous_scopes = w.tokens[existing].get("scopes", [])
                w.tokens[existing]["scopes"] = scopes
                return _helper_ok(
                    {
                        "access_token": existing,
                        "token_id": 1,
                        "client_id": w.tokens[existing].get("client"),
                        "scopes": scopes,
                        "reused": True,
                        "previous_scopes": previous_scopes,
                    }
                )
            w.minted += 1
            token = f"{prefix}{uuid.uuid4().hex}"
            client_name = params.get("client_name") or name
            roles = user.get("roles") or []
            w.tokens[token] = {
                "name": name,
                "scopes": scopes,
                "client": client_name,
                "role": roles[0] if roles else None,
            }
            return _helper_ok(
                {
                    "access_token": token,
                    "token_id": w.minted,
                    "client_id": client_name,
                    "scopes": scopes,
                    "reused": False,
                    "previous_scopes": None,
                }
            )
        if cmd == "revoke_token":
            target = params.get("access_token") or next(
                (t for t, v in w.tokens.items() if v.get("name") == params.get("name")), None
            )
            if target and target in w.tokens:
                del w.tokens[target]
                return _helper_ok({"deleted_tokens": [1], "deleted_clients": []})
            return _helper_ok({"deleted_tokens": [], "deleted_clients": []})
        if cmd == "register_sword_client":
            cid = params.get("client_id") or params.get("client_name")
            if not cid:
                return _helper_fail("InvalidArgument", "client_id or client_name is required")
            reg = params.get("registration_type", "Direct")
            previous = w.clients.get(cid)
            w.clients[cid] = {
                **(previous or {}),
                "name": cid,
                "register_type": reg,
                "duplicate_check": bool(params.get("duplicate_check", False)),
                "workflow_id": params.get("workflow_id"),
            }
            return _helper_ok(
                {
                    "created": previous is None,
                    "current": w.clients[cid],
                    "previous": previous,
                    "previous_delete_flow": None,
                }
            )
        if cmd == "set_client_field":
            cid, field, value = params.get("client_id"), params.get("field"), params.get("value")
            if cid not in w.clients:
                return _helper_fail("NotFound", f"client {cid} not found")
            key = (
                "register_type" if field in ("registration_type", "registration_type_id") else field
            )
            if key == "register_type" and value in (1, "1"):
                value = "Direct"
            elif key == "register_type" and value in (2, "2"):
                value = "Workflow"
            previous = w.clients[cid].get(key)
            w.clients[cid][key] = value
            return _helper_ok({"previous": previous, "value": value})
        if cmd == "create_record":
            title = params.get("title")
            if not isinstance(title, str) or not title:
                return _helper_fail("InvalidArgument", "title must be a non-empty string")
            recid = str(params["recid"]) if params.get("recid") else w.allocate_recid()
            created = recid not in w.records
            if created:
                w.records[recid] = w._new_record(
                    {"title": title, "doi": bool(params.get("with_doi"))}
                )
                w.deleted = [d for d in w.deleted if d != recid]
            doi = f"https://doi.org/ath-test/{recid}" if w.records[recid]["doi"] else None
            return _helper_ok(
                {
                    "recid": recid,
                    "uuid": str(uuid.uuid5(uuid.NAMESPACE_URL, recid)),
                    "created": created,
                    "doi": doi,
                }
            )
        if cmd == "delete_record":
            # Idempotent like the real helper; reports the state it found.
            recid = str(params.get("recid"))
            if params.get("restore"):
                restored = recid in w.deleted
                w.deleted = [d for d in w.deleted if d != recid]
                if restored:
                    w.records.setdefault(recid, w._new_record({"title": "restored"}))
                return _helper_ok({"recid": recid, "restored": restored})
            previous = (
                "deleted" if recid in w.deleted else "registered" if recid in w.records else None
            )
            if recid in w.records:
                del w.records[recid]
                w.deleted.append(recid)
            return _helper_ok(
                {"recid": recid, "previous": previous, "deleted": previous is not None}
            )
        if cmd == "insert_doi_pid":
            recid = str(params.get("recid"))
            if recid not in w.records:
                return _helper_fail("NotFound", f"record {recid} not found")
            created = not w.records[recid]["doi"]
            w.records[recid]["doi"] = True
            return _helper_ok(
                {
                    "doi": params.get("doi") or f"https://doi.org/ath-test/{recid}",
                    "created": created,
                }
            )
        if cmd == "orphan_record":
            recid = str(params.get("recid"))
            if params.get("restore"):
                w.records.setdefault(recid, w._new_record(params["restore"]))
                return _helper_ok({"restored_tables": ["records_metadata"]})
            rec = w.records.pop(recid, None)
            return _helper_ok({"backup": rec})
        if cmd == "snapshot":
            return _helper_ok(_snapshot(w, params))
        if cmd == "inject_fault":
            kind = params.get("kind")
            if not isinstance(kind, str):
                return _helper_fail("InvalidArgument", "kind must be a string")
            fault = {
                "kind": kind,
                "fault_id": len(w.helper_faults) + 1,
                "params": params.get("params") or {},
            }
            w.helper_faults.append(fault)
            return _helper_ok({"fault_id": fault["fault_id"], "info": {"stub": True}})
        if cmd == "restore_fault":
            kind = params.get("kind", "all")
            kept = [] if kind == "all" else [f for f in w.helper_faults if f["kind"] != kind]
            restored = [f["fault_id"] for f in w.helper_faults if f not in kept]
            w.helper_faults = kept
            return _helper_ok({"restored": restored, "swept": [], "warnings": []})
        if cmd == "list_faults":
            return _helper_ok(copy.deepcopy(w.helper_faults))
    return _helper_fail("UnknownCommand", f"unknown command: {cmd}")


def _snapshot(w: World, params: dict[str, Any]) -> dict[str, Any]:
    def digest(obj: Any) -> str:
        return _sha256(json.dumps(obj, sort_keys=True).encode())

    tables = params.get("tables") or ["records", "tokens", "sword_clients"]
    out: dict[str, Any] = {}
    recid = params.get("recid")
    for table in tables:
        if table == "records":
            rows = {r: digest(v) for r, v in w.records.items() if recid in (None, r)}
        elif table == "tokens":  # never the token value
            rows = {
                v.get("name", "?"): digest({**v, "revoked": t in w.revoked})
                for t, v in w.tokens.items()
            }
        elif table == "sword_clients":
            rows = {c: digest(v) for c, v in w.clients.items()}
        else:
            rows = {}
        out[table] = {"count": len(rows), "rows": rows}
    return out


def handle_control(world: World, req: Request) -> Response:
    sub = req.path[len(CONTROL_PREFIX) :]
    w = world
    try:
        payload = json.loads(req.body.decode("utf-8")) if req.body else {}
    except ValueError:
        return Response(400, {"error": "body is not JSON"})
    if sub == "state" and req.method == "GET":
        return Response(200, w.state())
    if sub == "reset" and req.method == "POST":
        w.reset(clear_log=bool(payload.get("clear_log", False)))
        w.log("INFO", "stub reset")
        return Response(200, {"ok": True})
    if sub == "fault" and req.method == "POST":
        if str(payload.get("code")) not in errtable.SPECS:
            return Response(400, {"error": f"unknown error code {payload.get('code')!r}"})
        fault = {
            "endpoint": payload.get("endpoint", "*"),
            "code": str(payload["code"]),
            "count": int(payload.get("count", 1)),
        }
        if "stage" in payload:
            fault["stage"] = payload["stage"]
        with w.lock:
            w.faults.append(fault)
        return Response(200, {"ok": True, "fault": fault})
    if sub == "fault" and req.method == "DELETE":
        with w.lock:
            w.faults.clear()
        return Response(200, {"ok": True})
    if sub == "helper" and req.method == "POST":
        return Response(
            200, run_helper(w, str(payload.get("cmd", "")), payload.get("params") or {})
        )
    if sub == "docker" and req.method == "POST":
        return Response(200, docker_action(w, payload))
    if sub == "logs" and req.method == "GET":
        query = urllib.parse.parse_qs(req.query)
        container = (query.get("container") or [""])[0]
        since = (query.get("since") or [None])[0]
        role = w.role_of_container(container)
        lines = w.db_log if role == "db" else w.log_since(since) if role in (None, "web") else []
        if role == "db" and since:
            floor = _parse_ts(since)
            lines = [
                x
                for x in lines
                if floor is None or (_parse_ts(x.split(" ", 1)[0]) or floor) >= floor
            ]
        return Response(
            200,
            None,
            raw=("\n".join(lines) + ("\n" if lines else "")).encode(),
            content_type="text/plain; charset=utf-8",
        )
    return Response(404, {"error": f"no control endpoint {req.method} {req.path}"})


def docker_action(w: World, payload: dict[str, Any]) -> dict[str, Any]:
    action, container = payload.get("action"), payload.get("container", "")
    role = w.role_of_container(container)
    if role is None:
        return {
            "ok": False,
            "stderr": f"Error response from daemon: No such container: {container}\n",
            "exit": 1,
        }
    with w.lock:
        if action == "stop":
            w.stopped.add(role)
        elif action == "start" or action == "restart":
            w.stopped.discard(role)
        elif action == "redis":
            return _redis(w, payload.get("args", []))
        else:
            return {"ok": False, "stderr": f"unsupported docker action {action!r}\n", "exit": 1}
    w.log("INFO", f"container {container} {action}")
    return {"ok": True, "stdout": container + "\n", "exit": 0}


def _redis(w: World, args: list[str]) -> dict[str, Any]:
    """A few single-key redis-cli commands (the DB number is ignored)."""
    now = time.time()
    for key in [k for k, (_v, e) in w.redis.items() if e is not None and e < now]:
        del w.redis[key]
    if not args:
        return {"ok": False, "stderr": "ERR wrong number of arguments\n", "exit": 1}
    cmd, rest = args[0].upper(), args[1:]
    if cmd == "SETEX" and len(rest) == 3:
        w.redis[rest[0]] = (rest[2], now + float(rest[1]))
        return {"ok": True, "stdout": "OK\n", "exit": 0}
    if cmd == "GET" and rest:
        value = w.redis.get(rest[0])
        return {"ok": True, "stdout": (value[0] if value else "") + "\n", "exit": 0}
    if cmd == "EXISTS" and rest:
        return {"ok": True, "stdout": f"{int(rest[0] in w.redis)}\n", "exit": 0}
    if cmd == "DEL" and rest:
        return {"ok": True, "stdout": f"{int(w.redis.pop(rest[0], None) is not None)}\n", "exit": 0}
    if cmd == "TTL" and rest:
        entry = w.redis.get(rest[0])
        ttl = -2 if entry is None else -1 if entry[1] is None else int(entry[1] - now)
        return {"ok": True, "stdout": f"{ttl}\n", "exit": 0}
    return {"ok": False, "stderr": f"ERR unknown command '{cmd}'\n", "exit": 1}


