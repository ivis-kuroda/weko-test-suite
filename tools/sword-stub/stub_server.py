class StubServer(ThreadingHTTPServer):
    daemon_threads = True
    allow_reuse_address = True

    def __init__(self, address: tuple[str, int], world: World) -> None:
        super().__init__(address, StubHandler)
        self.world = world
        self.rig = Rig(world)
        self.sessions: set[str] = set()

    def server_bind(self) -> None:
        # HTTPServer.server_bind resolves the host name, which can take seconds
        # without DNS; the rig only needs the bound address.
        import socketserver

        socketserver.TCPServer.server_bind(self)
        self.server_name, self.server_port = self.server_address[0], self.server_address[1]

    @property
    def url(self) -> str:
        host, port = self.server_address[:2]
        return f"http://{host}:{port}"


class StubHandler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"
    server: StubServer
    server_version = "sword-stub"

    def log_message(self, format: str, *args: Any) -> None:  # noqa: A002 - stdlib signature
        pass

    def _read_body(self) -> tuple[bytes, bool]:
        length = int(self.headers.get("Content-Length") or 0)
        if length > MAX_READ_BYTES:
            return b"", True
        return self.rfile.read(length), False

    def _dispatch(self) -> None:
        parsed = urllib.parse.urlsplit(self.path)
        path = urllib.parse.unquote(parsed.path)
        body, skipped = self._read_body()
        headers = {k.lower(): v for k, v in self.headers.items()}
        host = (
            headers.get("host")
            or f"{self.server.server_address[0]}:{self.server.server_address[1]}"
        )
        req = Request(self.command, path, parsed.query, headers, body, f"http://{host}", skipped)
        w = self.server.world
        try:
            if path.startswith(CONTROL_PREFIX):
                resp = handle_control(w, req)
            else:
                if "web" in w.stopped:
                    raise DropConnection
                if path.startswith(ADMIN_PREFIX):
                    resp = self._admin(req)
                else:
                    resp = self.server.rig.handle(req)
                    if resp.status < 400:
                        w.log("INFO", f"{self.command} {path} -> {resp.status}")
        except DropConnection:
            self.close_connection = True
            self.connection.close()
            return
        self._send(resp, close=skipped)

    def _admin(self, req: Request) -> Response:
        w, srv = self.server.world, self.server
        cookie = req.header("cookie") or ""
        session = re.search(r"stub_session=([0-9a-f]+)", cookie)
        authed = bool(session and session.group(1) in srv.sessions)
        sub = req.path[len(ADMIN_PREFIX) :] or "/"
        html = "text/html; charset=utf-8"
        if sub == "/" and req.method == "GET":
            page = dashboard_page(w) if authed else login_page()
            return Response(200, None, raw=page, content_type=html)
        if sub == "/login" and req.method == "POST":
            form = urllib.parse.parse_qs(req.body.decode("utf-8", "replace"))
            ok = (
                form.get("user", [""])[0] == w.admin["user"]
                and form.get("password", [""])[0] == w.admin["password"]
            )
            if not ok:
                w.log("WARNING", "admin login failed")
                return Response(401, None, raw=login_page("Invalid credentials"), content_type=html)
            sid = uuid.uuid4().hex
            srv.sessions.add(sid)
            w.log("INFO", "admin login ok")
            return Response(
                303,
                None,
                {"Location": "/stub-admin/", "Set-Cookie": f"stub_session={sid}; Path=/; HttpOnly"},
                raw=b"",
            )
        if sub == "/revoke" and req.method == "POST":
            if not authed:
                return Response(401, {"error": "login required"})
            name = json.loads(req.body.decode("utf-8") or "{}").get("name")
            with w.lock:
                hit = [t for t, v in w.tokens.items() if v.get("name") == name]
                w.revoked.update(hit)
            w.log("INFO", f"admin revoked token {name}")
            return Response(200, {"revoked": bool(hit), "name": name})
        return Response(404, None, raw=_page("not found", "<p>not found</p>"), content_type=html)

    def _send(self, resp: Response, close: bool = False) -> None:
        if resp.raw is not None:
            payload = resp.raw
        elif resp.body is None:
            payload = b""
        else:
            payload = json.dumps(resp.body, ensure_ascii=False).encode("utf-8")
        self.send_response(resp.status)
        self.send_header(*STUB_HEADER)
        if payload or resp.status not in (204, 304):
            self.send_header("Content-Type", resp.content_type)
        self.send_header("Content-Length", str(len(payload)))
        for key, value in resp.headers.items():
            self.send_header(key, value)
        if close:
            self.send_header("Connection", "close")
            self.close_connection = True
        self.end_headers()
        if self.command != "HEAD":
            self.wfile.write(payload)

    do_GET = do_POST = do_PUT = do_DELETE = do_PATCH = do_HEAD = do_OPTIONS = _dispatch


def make_server(
    config: dict[str, Any] | None = None,
    log_file: str | None = None,
    host: str = "127.0.0.1",
    port: int = 0,
) -> StubServer:
    """Builds a server (not yet serving). `port=0` picks a free port."""
    return StubServer((host, port), World(config or {}, log_file))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=BANNER)
    parser.add_argument("--config", help="stub.json describing tokens, clients and records")
    parser.add_argument("--log-file", help="application log (WARNING 4xx, ERROR 5xx)")
    parser.add_argument("--host", default="127.0.0.1")
    parser.add_argument("--port", type=int, default=8080, help="0 picks a free port")
    parser.add_argument("--port-file", help="write the chosen port here once listening")
    args = parser.parse_args(argv)
    config = json.loads(Path(args.config).read_text(encoding="utf-8")) if args.config else {}
    server = make_server(config, args.log_file, args.host, args.port)
    print(BANNER, file=sys.stderr, flush=True)
    print(f"sword-stub listening on {server.url}", file=sys.stderr, flush=True)
    if args.port_file:
        Path(args.port_file).write_text(str(server.server_address[1]), encoding="utf-8")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()
    return 0


