class Request:
    def __init__(
        self,
        method: str,
        path: str,
        query: str,
        headers: dict[str, str],
        body: bytes,
        base_url: str,
        body_skipped: bool = False,
    ):
        self.method, self.path, self.query = method, path, query
        self.headers = headers  # keys lower-cased
        self.body, self.base_url, self.body_skipped = body, base_url, body_skipped
        self.token: dict[str, Any] | None = None

    def header(self, name: str) -> str | None:
        return self.headers.get(name.lower())

    @property
    def parts(self) -> list[Part]:
        return parse_multipart(self.header("content-type") or "", self.body)


class Response:
    def __init__(
        self,
        status: int,
        body: Any = None,
        headers: dict[str, str] | None = None,
        raw: bytes | None = None,
        content_type: str = "application/json",
    ):
        self.status, self.body, self.headers = status, body, headers or {}
        self.raw, self.content_type = raw, content_type


def normalise_endpoint(method: str, path: str) -> str:
    return f"{method} " + re.sub(r"^/sword/deposit/[^/]+$", "/sword/deposit/{recid}", path)


class Rig:
    """The SWORD behaviour on top of a World."""

    def __init__(self, world: World) -> None:
        self.w = world

    # -- error documents --
    def error_response(self, req: Request, err: SwordError | PlainError | Fault) -> Response:
        w = self.w
        endpoint = f"{req.method} {req.path}"
        if isinstance(err, PlainError):
            if err.status == 401:
                type_, message = "AuthenticationRequired", "Authentication is required."
            else:
                type_, message = "Forbidden", "Not allowed operation in your role or token scope."
            w.log("ERROR", f"{message} ({endpoint} -> {err.status})")
            return Response(err.status, self._error_doc(type_, message))
        if isinstance(err, Fault):
            code = err.code
            sw = SwordError(code, recid=req.path.rsplit("/", 1)[-1])
        else:
            sw = err
        text = f"[{sw.code}] {endpoint}: {sw.message}"
        if sw.status >= 500:
            w.log("ERROR", text + "\n" + _fake_traceback(sw, isinstance(err, Fault)))
        else:
            if sw.log and w.settings.get("faithful_log", True):
                w.log("ERROR", sw.log)
            w.log("WARNING", text)
        return Response(
            sw.status, self._error_doc(sw.type, f"{errtable.PREFIX}{sw.code}: {sw.message}")
        )

    @staticmethod
    def _error_doc(type_: str, error: str) -> dict[str, Any]:
        return {
            "@context": errtable.JSON_LD_CONTEXT,
            "@type": type_,
            "timestamp": utc_now().strftime("%Y-%m-%dT%H:%M:%SZ"),
            "error": error,
        }

    # -- stages --
    def maybe_fault(self, req: Request, stage: str) -> None:
        w = self.w
        endpoint = normalise_endpoint(req.method, req.path)
        with w.lock:
            for fault in list(w.faults):
                target = fault.get("endpoint", "*")
                if target not in ("*", endpoint, endpoint.split(" ", 1)[1], req.method):
                    continue
                code = str(fault["code"])
                default_stage = "auth" if code in ("3108", "3109", "3110") else "process"
                if fault.get("stage", default_stage) != stage:
                    continue
                if fault.get("count", 1) > 0:
                    fault["count"] -= 1
                    if fault["count"] == 0:
                        w.faults.remove(fault)
                raise Fault(code, "fault")

    def container_effects(self, req: Request, stage: str) -> None:
        stopped = self.w.stopped
        if stage == "auth" and "db" in stopped:
            raise Fault("3108", "docker")
        if stage == "process":
            if "redis" in stopped and req.method in ("PUT", "DELETE"):
                raise Fault("3109", "docker")
            if "search" in stopped and req.path.startswith("/sword/deposit/"):
                raise Fault("3110", "docker")

    def authenticate(self, req: Request) -> dict[str, Any]:
        header = req.header("authorization")
        if not header or not header.lower().startswith("bearer "):
            raise PlainError(401)
        value = header.split(None, 1)[1].strip()
        token = self.w.tokens.get(value)
        if token is None or value in self.w.revoked:
            raise PlainError(401)
        req.token = token
        return token

    def check_rate(self) -> None:
        limit = self.w.settings.get("rate_limit")
        if limit:
            self.w.rate_hits += 1
            if self.w.rate_hits > int(limit):
                raise SwordError("2301")

    def require_scopes(self, token: dict[str, Any], *scopes: str) -> None:
        if not set(scopes) <= set(token.get("scopes", [])):
            raise PlainError(403)

    def require_role(self, token: dict[str, Any]) -> None:
        if token.get("role") not in self.w.settings["roles_allowed"]:
            raise PlainError(403)

    def check_on_behalf_of(self, req: Request) -> None:
        if not self.w.settings.get("on_behalf_of") and req.header("on-behalf-of"):
            raise SwordError("1202", log="Not support On-Behalf-Of but request has it.")

    def resolve_obo(self, req: Request) -> None:
        obo = req.header("on-behalf-of")
        if not obo:
            return
        users = self.w.settings.get("obo_users", {})
        if obo not in users:
            raise SwordError("1203")
        if not users[obo]:
            raise SwordError("1204")

    def check_package_contents(self, req: Request) -> Part:
        files = [p for p in req.parts if p.filename is not None]
        if not files or not any(p.name == "file" for p in files):
            raise SwordError("1301", log="No file part.")
        file = next(p for p in files if p.name == "file")
        if file.filename == "":
            raise SwordError("1302", log="No selected file.")
        max_size = int(self.w.settings["max_upload_size"])
        content_length = req.header("content-length")
        if int(content_length or len(file.data)) > max_size:
            raise SwordError(
                "1305",
                log=f"Content size is too large. (request:{content_length}, maxUploadSize:{max_size})",  # noqa: E501
                content_length=content_length,
                max_upload_size=max_size,
            )
        accept = self.w.settings["accept_archive_format"]
        req_ct = (req.header("content-type") or "").split(";")[0] or None
        file_ct = (file.content_type or "").split(";")[0] or None
        failed = None
        if req_ct not in accept:
            failed = req_ct
            if file_ct not in accept:
                failed = file_ct
        if failed is not None:
            raise SwordError(
                "1401", log=f"Not accept Content-Type: {failed}", failed_content_type=failed
            )
        packaging = req.header("packaging")
        accepted_packaging = self.w.settings["accept_packaging"]
        if "*" not in accepted_packaging:
            if packaging not in accepted_packaging:
                raise SwordError(
                    "1402", log=f"Not accept packaging: {packaging}", packaging=packaging
                )
        elif packaging is None:
            raise SwordError(
                "1403", log="Packaging is required, but not contained in request headers."
            )
        return file

    # -- deposit helpers --
    def status_document(self, req: Request, recid: str) -> dict[str, Any]:
        rec = self.w.records.get(recid)
        if rec is None:
            raise SwordError("2101", log=f"Item not found. (recid={recid})", recid=recid)
        url = f"{req.base_url}/sword/deposit/{recid}"
        return {
            "@context": errtable.JSON_LD_CONTEXT,
            "@id": url,
            "@type": "Status",
            "service": f"{req.base_url}/sword/service-document",
            "state": [
                {
                    "@id": "http://purl.org/net/sword/3.0/state/accepted",
                    "description": "The item is held by the stub.",
                }
            ],
            "links": [
                {
                    "@id": url,
                    "rel": ["http://purl.org/net/sword/3.0/terms/statusDocument"],
                    "contentType": "application/json",
                    "status": "http://purl.org/net/sword/3.0/filestate/ingested",
                }
            ],
            "metadata": {"@context": errtable.JSON_LD_CONTEXT, "dc:title": rec["title"]},
        }

    def _client_for(self, req: Request) -> dict[str, Any] | None:
        client = (req.token or {}).get("client")
        return self.w.clients.get(client) if client else None

    def inspect(
        self, req: Request, file: Part, recid: str | None
    ) -> tuple[dict[str, Any] | None, str, list[dict[str, Any]], dict[str, Any]]:
        """Filename, packaging, OBO, digest, format, client, workflow scope, item check.

        Returns (client, format, items, ...) for the caller; raises SwordError.
        """
        disposition = req.header("content-disposition") or ""
        kind, _, rest = disposition.partition(";")
        filename = _disp_param(rest, "filename") if rest else None
        if kind.strip().lower() != "attachment" or filename is None:
            raise SwordError("1303", log="Cannot get filename by Content-Disposition.")
        match = next((p for p in req.parts if p.filename == filename), None)
        if match is None:
            raise SwordError(
                "1304", log=f"Not found {filename} in request body.", filename=filename
            )
        file = match
        packaging = req.header("packaging") or ""
        try:
            archive = zipfile.ZipFile(io.BytesIO(file.data))
        except zipfile.BadZipFile as exc:
            raise RuntimeError(f"File is not a zip file: {exc}") from exc
        with archive:
            fmt = detect_format(archive, packaging)
            self.resolve_obo(req)
            if self.w.settings["digest_verification"]:
                digest = req.header("digest")
                if (
                    not isinstance(digest, str)
                    or not digest.startswith("SHA-256=")
                    or digest.split("SHA-256=")[-1] != _sha256(file.data)
                ):
                    raise SwordError("1306", log="Failed to verify request body and digest.")
            client = self._client_for(req)
            if not self.w.settings["import_enabled"].get(fmt, True):
                raise SwordError("1409", file_format=fmt)
            if fmt == "XML" and client is not None and client.get("register_type") == "Direct":
                raise SwordError("1410")
            if client is None:
                raise SwordError("2103", log="No SWORD API setting found for client.")
            register_type = client.get("register_type", "Direct")
            if register_type == "Workflow":
                if client.get("workflow") == "missing":
                    raise SwordError("2104")
                if client.get("workflow") == "not_registration":
                    raise SwordError("2105")
                assert req.token is not None
                if SCOPE_ACTIVITY not in req.token.get("scopes", []):
                    raise SwordError("1201", log="Required scopes for activity are not satisfied.")
            if fmt == "JSON":
                items, detail = _json_items(archive, packaging)
            elif fmt == "XML":
                items, detail = _xml_items(archive)
            else:
                items, detail = _csv_items(archive)
        if detail:
            raise SwordError("1501", log=f"Error in check_import_items: {detail}", detail=detail)
        for item in items:
            if not item["title"]:
                detail = "title is required"
                raise SwordError(
                    "1501", log=f"Error in check_import_items: {detail}", detail=detail
                )
            if item["id"] is None:
                item["status"] = "new"
            elif item["id"] in self.w.records:
                item["status"] = "exists"
            else:
                detail = f"item {item['id']} does not exist"
                raise SwordError(
                    "1501", log=f"Error in check_import_items: {detail}", detail=detail
                )
        if not items:
            raise SwordError(
                "1501", log="Error in check_import_items: item_missing", detail="item_missing"
            )
        return client, fmt, items, {}

    def is_duplicate(self, title: str, exclude: str | None = None) -> bool:
        return any(rec["title"] == title for rid, rec in self.w.records.items() if rid != exclude)

    def lock_item(self, recid: str) -> None:
        rec = self.w.records[recid]
        now = time.monotonic()
        if rec["locked"] or rec["locked_until"] > now or self._redis_locked(recid):
            raise SwordError(
                "2201", log=f"Item {recid} will be edited by another process.", recid=recid
            )
        rec["locked_until"] = now + float(self.w.settings.get("lock_seconds", 0))

    def _redis_locked(self, recid: str) -> bool:
        now = time.time()
        for key, (_value, expiry) in self.w.redis.items():
            if expiry is not None and expiry < now:
                continue
            m = re.search(r"lock.*?(\d+)$", key)
            if m and m.group(1) == recid:
                return True
        return False

