class World:
    """Tokens, clients, records, faults and logs. One lock guards everything."""

    def __init__(self, config: dict[str, Any], log_file: str | None = None) -> None:
        self.lock = threading.RLock()
        self.initial = _merge(DEFAULT_CONFIG, config)
        self.log_file = log_file
        self.log_lines: list[str] = []
        self.log_times: list[datetime] = []
        self.db_log: list[str] = []
        self.rate_hits = 0
        self.reset(clear_log=True)

    # -- lifecycle --
    def reset(self, clear_log: bool = False) -> None:
        with self.lock:
            cfg = copy.deepcopy(self.initial)
            self.tokens: dict[str, dict[str, Any]] = cfg["tokens"]
            self.revoked: set[str] = set(cfg["revoked"])
            self.clients: dict[str, dict[str, Any]] = cfg["clients"]
            self.records: dict[str, dict[str, Any]] = {
                str(k): self._new_record(v) for k, v in cfg["records"].items()
            }
            self.next_recid: int = int(cfg["next_recid"])
            self.users: dict[str, dict[str, Any]] = cfg["users"]
            self.containers_cfg: dict[str, str] = cfg["containers"]
            self.admin: dict[str, str] = cfg["admin"]
            self.settings: dict[str, Any] = cfg["settings"]
            self.faults: list[dict[str, Any]] = []
            self.helper_faults: list[dict[str, Any]] = []
            self.stopped: set[str] = set()  # roles: web / db / redis / search
            self.redis: dict[str, tuple[str, float | None]] = {}
            self.deleted: list[str] = []
            self.rate_hits = 0
            self.minted = 0
            if clear_log:
                self.log_lines.clear()
                self.log_times.clear()
                self.db_log.clear()
                if self.log_file:
                    Path(self.log_file).write_text("", encoding="utf-8")

    @staticmethod
    def _new_record(data: dict[str, Any] | None = None) -> dict[str, Any]:
        rec = {
            "title": "Stub item",
            "doi": False,
            "locked": False,
            "editing": False,
            "importing": False,
            "version": 1,
            "locked_until": 0.0,
        }
        rec.update(data or {})
        return rec

    def role_of_container(self, name: str) -> str | None:
        for role, container in self.containers_cfg.items():
            if container == name:
                return role
        return None

    # -- logging --
    def log(self, level: str, message: str) -> None:
        """One application-log line. Never receives a secret."""
        now = utc_now()
        line = f"{iso(now)} {level} sword-stub: {message}"
        with self.lock:
            self.log_lines.append(line)
            self.log_times.append(now)
            if self.log_file:
                with open(self.log_file, "a", encoding="utf-8") as handle:
                    handle.write(line + "\n")

    def log_since(self, since: str | None) -> list[str]:
        with self.lock:
            lines = list(self.log_lines)
            if not since:
                return lines
            times = list(self.log_times)
        floor = _parse_ts(since)
        return [line for line, at in zip(lines, times, strict=True) if floor is None or at >= floor]

    # -- records --
    def allocate_recid(self) -> str:
        with self.lock:
            while str(self.next_recid) in self.records or str(self.next_recid) in self.deleted:
                self.next_recid += 1
            recid = str(self.next_recid)
            self.next_recid += 1
            return recid

    def state(self) -> dict[str, Any]:
        with self.lock:
            return {
                "stub": "sword-mechanics-rig",
                "tokens": {
                    t.get("name", "?"): {
                        "scopes": t.get("scopes", []),
                        "role": t.get("role"),
                        "client": t.get("client"),
                        "revoked": tok in self.revoked,
                    }
                    for tok, t in self.tokens.items()
                },
                "revoked": sorted(
                    self.tokens[t].get("name", "?") for t in self.revoked if t in self.tokens
                ),
                "clients": copy.deepcopy(self.clients),
                "records": copy.deepcopy(self.records),
                "deleted": list(self.deleted),
                "next_recid": self.next_recid,
                "faults": copy.deepcopy(self.faults),
                "helper_faults": copy.deepcopy(self.helper_faults),
                "stopped": sorted(self.stopped),
                "containers": dict(self.containers_cfg),
                "settings": copy.deepcopy(self.settings),
                "log_lines": len(self.log_lines),
            }


def _parse_ts(text: str) -> datetime | None:
    try:
        return datetime.fromisoformat(text.replace("Z", "+00:00")).astimezone(UTC)
    except ValueError:
        return None


